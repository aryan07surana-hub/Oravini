// Matches "/f/:slug/:stepSlug"-style patterns against a concrete path.
// Trailing slashes are ignored; query strings never reach this (req.path).
export function matchesSpaRoute(pathname: string): boolean {
  const norm = pathname.length > 1 ? pathname.replace(/\/+$/, "") : pathname;
  const segs = norm.split("/").filter(Boolean);
  for (const pattern of SPA_ROUTES) {
    const psegs = pattern.split("/").filter(Boolean);
    if (psegs.length !== segs.length) continue;
    let ok = true;
    for (let i = 0; i < psegs.length; i++) {
      if (psegs[i].startsWith(":")) continue;
      if (psegs[i] !== segs[i]) { ok = false; break; }
    }
    if (ok) return true;
  }
  return false;
}

